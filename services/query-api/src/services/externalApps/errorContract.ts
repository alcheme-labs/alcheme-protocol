export function buildExternalProgramErrorContract(): ExternalProgramErrorContract {
  return {
    version: APP_TRUST_ROOT_ERROR_CONTRACT_VERSION,
    errors: EXTERNAL_PROGRAM_ERROR_CONTRACT_ENTRIES,
  };
}

export function getExternalProgramErrorHttpStatus(code: string): number | null {
  return (
    EXTERNAL_PROGRAM_ERROR_CONTRACT_ENTRIES.find((item) => item.code === code)
      ?.httpStatus ?? null
  );
}

export function isExternalProgramErrorContractCode(code: string): boolean {
  return EXTERNAL_PROGRAM_ERROR_CONTRACT_ENTRIES.some(
    (item) => item.code === code,
  );
}

function entry(
  code: string,
  category: AppTrustRootErrorContractEntry["category"],
  retryable: boolean,
  developerAction: string,
  httpStatus: number,
): AppTrustRootErrorContractEntry {
  return defineAppTrustRootErrorContractEntry({
    code,
    category,
    retryable,
    developerAction,
    userCopyKey: `external_program.${code}`,
    httpStatus,
  });
}
